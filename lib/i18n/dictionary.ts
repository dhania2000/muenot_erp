/**
 * Looks up a static translation for a piece of UI text. Matching is
 * case-insensitive and whitespace-trimmed. Returns null when there is no
 * dictionary entry (the caller should leave the original English text as-is
 * — there is no AI/network fallback).
 */
export function lookupTranslation(text: string, lang: string): string | null {
  const dict = TRANSLATIONS[lang]
  if (!dict) return null
  const key = text.trim().toLowerCase()
  return dict[key] ?? null
}
